# Rasterizes Pillow's bundled Aileron (CC0) into src/gfx/font_data.h as 8-bit coverage.
# Run from the repo root. The "bold" face is just the regular one smeared 1px,
# Pillow only ships the one weight.
import sys
from PIL import Image, ImageChops, ImageDraw, ImageFont

LP = 1  # left padding so glyphs with negative bearing don't get clipped
FACES = [("ui", 13, False), ("small", 11, False), ("bold", 13, True), ("big", 22, False)]


def render(font, ch, asc, h, wid, bold):
    im = Image.new("L", (wid, h), 0)
    ImageDraw.Draw(im).text((LP, asc), ch, font=font, fill=255, anchor="ls")
    if bold:
        im2 = Image.new("L", (wid, h), 0)
        ImageDraw.Draw(im2).text((LP + 1, asc), ch, font=font, fill=255, anchor="ls")
        im = ImageChops.lighter(im, im2)
    return im


def build(size, bold):
    font = ImageFont.load_default(size)
    asc, desc = font.getmetrics()
    h = asc + desc + 1
    wid = size * 2 + 4
    imgs, widths = [], []
    cw = 0
    for code in range(32, 127):
        ch = chr(code)
        im = render(font, ch, asc, h, wid, bold)
        bbox = im.getbbox()
        cw = max(cw, bbox[2] if bbox else 0)
        adv = int(round(font.getlength(ch))) + (1 if bold else 0)
        widths.append(max(adv, 3) if ch == " " else max(adv, 1))
        imgs.append(im)
    data = []
    for im in imgs:
        px = im.load()
        for y in range(h):
            for x in range(cw):
                data.append(px[x, y])
    return h, cw, widths, data


out = ["/* generated by tools/genfont.py, don't hand edit */",
       "#define FONT_FIRST 32", "#define FONT_COUNT 95", "#define FONT_LP %d" % LP,
       "typedef struct { int h, cw; const unsigned char *w, *d; } Font;"]
inits = []
for i, (name, size, bold) in enumerate(FACES):
    h, cw, widths, data = build(size, bold)
    out.append("static const unsigned char font%d_w[] = {%s};" % (i, ",".join(map(str, widths))))
    out.append("static const unsigned char font%d_d[] = {%s};" % (i, ",".join(map(str, data))))
    inits.append("{%d,%d,font%d_w,font%d_d}" % (h, cw, i, i))
out.append("static const Font fonts[%d] = {%s};" % (len(FACES), ",".join(inits)))
open(sys.argv[1] if len(sys.argv) > 1 else "src/gfx/font_data.h", "w").write("\n".join(out) + "\n")
