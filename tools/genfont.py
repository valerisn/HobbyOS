# Rasterizes Pillow's bundled Aileron (CC0) into src/font_data.h.
# Proportional on purpose: forcing it into a monospace cell looked awful.
from PIL import Image, ImageDraw, ImageFont
import sys

H = 14
BASE = 11
font = ImageFont.load_default(12)
widths, rows = [], []
for code in range(32, 127):
    ch = chr(code)
    im = Image.new("L", (16, 16), 0)
    ImageDraw.Draw(im).text((0, BASE), ch, font=font, fill=255, anchor="ls")
    cols = [x for x in range(16) if any(im.getpixel((x, y)) > 96 for y in range(H))]
    w = max(int(round(font.getlength(ch))), (max(cols) + 1) if cols else 0)
    w = max(3, min(15, w)) + 1
    widths.append(w)
    r = []
    for y in range(H):
        v = 0
        for x in range(16):
            if im.getpixel((x, y)) > 96:
                v |= 1 << (15 - x)
        r.append(v)
    rows.append(r)

out = ["/* generated by tools/genfont.py, don't hand edit */",
       "#define FONT_H %d" % H, "#define FONT_FIRST 32", "#define FONT_COUNT 95",
       "static const unsigned char font_w[FONT_COUNT] = {" + ",".join(map(str, widths)) + "};",
       "static const unsigned short font_rows[FONT_COUNT][FONT_H] = {"]
for r in rows:
    out.append("{" + ",".join("0x%04x" % v for v in r) + "},")
out.append("};")
open(sys.argv[1] if len(sys.argv) > 1 else "src/font_data.h", "w").write("\n".join(out) + "\n")
